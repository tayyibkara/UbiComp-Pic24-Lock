void DrawChar(uint8_t x, uint8_t y, char c) {
    int index = 0;
    if (c >= '0' && c <= '9') index = 1 + (c - '0');
    else if (c >= 'A' && c <= 'Z') index = 11 + (c - 'A');
    else if (c == '*') index = 37;
    else if (c == '>') index = 38;
    else if (c == '.') index = 39;
    
    for (int col = 0; col < 5; col++) {
        uint8_t columnData = FONT[index][col];
        for (int row = 0; row < 8; row++) {
            if ((columnData >> row) & 0x01) PutPixel(x + col, y + row);
        }
    }
}

void DrawString(uint8_t x, uint8_t y, char* str) {
    int cursorX = x;
    while (*str) {
        DrawChar(cursorX, y, *str);
        cursorX += 6; 
        str++;
    }
}

void DisplayPasswordProgress(int stepsEntered) {
    SetColor(BLACK);
    // Clear area where asterisks go
    for (int i = 0; i < 50; i++) {
        for (int j = 0; j < 8; j++) PutPixel(10 + i, 30 + j);
    }
    SetColor(WHITE);
    for (int i = 0; i < stepsEntered; i++) {
        DrawChar(10 + (i * 6), 30, '*');
    }
}

void DisplayTimer(int secondsRemaining) {
    SetColor(BLACK);
    // Clear timer area
    for (int i = 70; i < 128; i++) {
        for (int j = 0; j < 16; j++) PutPixel(i, 20 + j);
    }
    SetColor(WHITE);
    if (secondsRemaining < 10) {
        DrawChar(70, 20, '0' + secondsRemaining);
    } else {
        DrawChar(70, 20, '0' + (secondsRemaining / 10));
        DrawChar(76, 20, '0' + (secondsRemaining % 10));
    }
    DrawString(82, 20, "SEC");
}

void ShowCalibrationScreen(void) {
    SetColor(BLACK); ClearDevice();
    SetColor(WHITE); DrawString(10, 20, "CALIBRATING");
}